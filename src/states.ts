const NAMES = new Map(
  Object.values(STATES).map((name) => [key(name), name] as const),
)
NAMES.set(key('Virgin Islands'), STATES.VI!)
NAMES.set(key('Washington DC'), STATES.DC!)

function key(value: string): string {
  return value.toLowerCase().replace(/[^a-z]/g, '')
}

/** "California", "california" or "CA" as the dataset writes it, or null. */
export function findState(value: string): string | null {
  const trimmed = value.trim()
  return STATES[trimmed.toUpperCase()] ?? NAMES.get(key(trimmed)) ?? null
}
